const player = () => G.player as unknown as Player;
const num = (v: unknown, d: number) => (v == null ? d : Number(v));
const bool = (v: unknown, d: boolean) => (v == null ? d : v !== false);
const str = (v: unknown) => (v == null ? null : String(v));
const pkmnArg = (v: unknown) => (v instanceof Pokemon ? v : v == null ? null : String(v));

// The naming screen used by pbNickname.
PokemonUIHooks.enterPokemonName = (helptext, minLength, maxLength, initialText, pkmn) =>
  pbEnterPokemonName(helptext, minLength, maxLength, initialText, pkmn);

// --- Items (012_Overworld/001_Overworld.rb) -----------------------------------
defineScript("pbItemBall", (_c, item, quantity) => pbItemBall(String(item), num(quantity, 1)));
defineScript("pbReceiveItem", (_c, item, quantity) => pbReceiveItem(String(item), num(quantity, 1)));
defineScript("pbBuyPrize", (_c, item, quantity) => pbBuyPrize(String(item), num(quantity, 1)));

// --- Pokémon (019_Utilities/002_Utilities_Pokemon.rb) -----------------------------
defineScript("pbBoxesFull?", () => pbBoxesFull());
defineScript("pbAddPokemon", (_c, pkmn, level, seeForm) => pbAddPokemon(pkmnArg(pkmn), num(level, 1), bool(seeForm, true)));
defineScript("pbAddPokemonSilent", (_c, pkmn, level, seeForm) => pbAddPokemonSilent(pkmnArg(pkmn), num(level, 1), bool(seeForm, true)));
defineScript("pbAddToParty", (_c, pkmn, level, seeForm) => pbAddToParty(pkmnArg(pkmn), num(level, 1), bool(seeForm, true)));
defineScript("pbAddToPartySilent", (_c, pkmn, level, seeForm) =>
  pbAddToPartySilent(pkmnArg(pkmn), level == null ? null : Number(level), bool(seeForm, true)));
defineScript("pbAddForeignPokemon", (_c, pkmn, level, ownerName, nickname, ownerGender, seeForm) =>
  pbAddForeignPokemon(pkmnArg(pkmn), num(level, 1), str(ownerName), str(nickname), num(ownerGender, 0), bool(seeForm, true)));
for (const name of ["pbGenerateEgg", "pbAddEgg", "pbGenEgg"]) {
  defineScript(name, (_c, pkmn, text) => pbGenerateEgg(pkmnArg(pkmn), text == null ? "" : String(text)));
}
defineScript("pbStorePokemon", (_c, pkmn) => pbStorePokemon(pkmn as Pokemon));
defineScript("pbNicknameAndStore", (_c, pkmn) => pbNicknameAndStore(pkmn as Pokemon));
defineScript("pbFirstAblePokemon", (_c, variableID) => pbFirstAblePokemon(Number(variableID)));
defineScript("pbBalancedLevel", (_c, party) => pbBalancedLevel(party as Pokemon[]));
defineScript("pbSize", (_c, pkmn) => pbSize(pkmn as Pokemon));
defineScript("pbHasEgg?", (_c, species) => pbHasEgg(String(species)));
defineScript("pbNumOwnedSpecies", (_c, species, attribute, value) => pbNumOwnedSpecies(str(species), str(attribute), value ?? null));
defineScript("Pokemon.new", (_c, species, level, owner, withMoves, recheckForm) =>
  new Pokemon(String(species), Number(level), owner === undefined ? undefined : (owner as never), bool(withMoves, true), bool(recheckForm, true)));

/** Interpreter#pbGetPokemon(id): $player.party[pbGet(id)]. */
defineScript("pbGetPokemon", (_c, id) => player().party[Number(G.gameVariables.get(Number(id)))] ?? null);

/**
 * pbHasSpecies? isn't defined in v20.1 (it was removed in v19; events calling
 * it raise NoMethodError in the original). Kept working as $player.has_species?.
 */
defineScript("pbHasSpecies?", (_c, species, form) => {
  console.warn("pbHasSpecies? doesn't exist in Essentials v20.1; using $player.has_species?");
  return player().hasSpecies(String(species), num(form, -1));
});

// Essentials Deluxe / evolution events
defineScript("pbEvolutionEvent", (_c, number) => pbEvolutionEvent(Number(number)));

// --- Trainers (015_Trainers and player/002_Trainer_LoadAndNew.rb) -----------------
