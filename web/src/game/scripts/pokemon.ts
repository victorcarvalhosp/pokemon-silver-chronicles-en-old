defineScript("pbUnlockWallpaper", (_c, index) => pbUnlockWallpaper(Number(index)));
defineScript("pbLockWallpaper", (_c, index) => pbLockWallpaper(Number(index)));

// --- Pokemon Silver Chronicles Helpers (Utils.rb) -------------------------------
defineScript("is_first_pokemon_species?", (_c, species, form) => isFirstPokemonSpecies(String(species), num(form, -1)));
defineScript("switchPositionIfHasPokemon", (ctx, species, form) =>
  switchPositionIfHasPokemon(String(species), num(form, -1), (on) => {
    // FollowingPkmn.toggle_off / toggle_on (Following Pokémon EX port)
    void evaluateAsync({ call: on ? "FollowingPkmn.toggle_on" : "FollowingPkmn.toggle_off", args: [] }, ctx);
  }));

